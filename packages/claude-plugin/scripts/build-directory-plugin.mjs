#!/usr/bin/env node
// Writes the Claude plugin directory's variant of this plugin to
// claude-plugin-directory/ at the repo root (openspec deploy-hosted-gateway).
// The directory only accepts local MCP servers from Verified organizations, so
// this variant has the same skills, agent and icon but connects to the hosted
// gateway over HTTP: no package.json, lockfile or launcher. It is only for the
// directory submission; the marketplace plugin people install themselves
// (packages/claude-plugin) keeps the local server.
//
//   node ./scripts/build-directory-plugin.mjs           write it
//   node ./scripts/build-directory-plugin.mjs --check   fail if the committed copy is stale
import { promises as fs } from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';

const HOSTED_URL = 'https://open-design.feimacode.com/mcp';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const pluginRoot = path.resolve(__dirname, '..');
const outRoot = path.resolve(pluginRoot, '..', '..', 'claude-plugin-directory');

// Copied as they are from the marketplace plugin.
const COPIED = ['.claude-plugin/icon.png', 'agents', 'skills'];

const README = `# Open Design: Claude plugin directory variant

Generated by \`packages/claude-plugin/scripts/build-directory-plugin.mjs\`; don't edit it here.

This is the plugin submitted to the Claude plugin directory. It has the same skills and agent as
\`packages/claude-plugin\`, but its MCP server is the hosted gateway at ${HOSTED_URL}, because the
directory only accepts MCP servers that run on the user's computer from Verified organizations.
To run the server on your own computer, install the plugin from this repository's marketplace instead.
`;

async function walk(dir, base = dir) {
  const files = [];
  for (const entry of await fs.readdir(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) files.push(...(await walk(full, base)));
    else files.push(path.relative(base, full));
  }
  return files;
}

/** Every file of the variant, as relative path -> contents. */
async function expectedFiles() {
  const files = new Map();
  for (const item of COPIED) {
    const src = path.join(pluginRoot, item);
    if ((await fs.stat(src)).isDirectory()) {
      for (const rel of await walk(src)) files.set(path.join(item, rel), await fs.readFile(path.join(src, rel)));
    } else {
      files.set(item, await fs.readFile(src));
    }
  }
  const manifest = JSON.parse(await fs.readFile(path.join(pluginRoot, '.claude-plugin', 'plugin.json'), 'utf8'));
  files.set('.claude-plugin/plugin.json', Buffer.from(`${JSON.stringify(manifest, null, 2)}\n`));
  const mcp = { mcpServers: { 'open-design': { type: 'http', url: HOSTED_URL } } };
  files.set('.mcp.json', Buffer.from(`${JSON.stringify(mcp, null, 2)}\n`));
  files.set('README.md', Buffer.from(README));
  return files;
}

async function main() {
  const check = process.argv.includes('--check');
  const expected = await expectedFiles();
  const existing = (await fs.stat(outRoot).catch(() => null)) ? await walk(outRoot) : [];

  if (check) {
    const problems = [];
    for (const [rel, content] of expected) {
      const actual = await fs.readFile(path.join(outRoot, rel)).catch(() => null);
      if (!actual) problems.push(`missing ${rel}`);
      else if (!actual.equals(content)) problems.push(`stale ${rel}`);
    }
    for (const rel of existing) if (!expected.has(rel)) problems.push(`unexpected ${rel}`);
    if (problems.length) {
      console.error(`claude-plugin-directory/ is out of date (run npm run build-directory-plugin):\n  ${problems.join('\n  ')}`);
      process.exit(1);
    }
    console.log(`✓ claude-plugin-directory/ matches the plugin (${expected.size} files, server ${HOSTED_URL})`);
    return;
  }

  for (const rel of existing) if (!expected.has(rel)) await fs.rm(path.join(outRoot, rel));
  for (const [rel, content] of expected) {
    await fs.mkdir(path.dirname(path.join(outRoot, rel)), { recursive: true });
    await fs.writeFile(path.join(outRoot, rel), content);
  }
  console.log(`Wrote claude-plugin-directory/ (${expected.size} files, server ${HOSTED_URL}).`);
}

main().catch((err) => {
  console.error(err instanceof Error ? err.message : err);
  process.exit(1);
});
