#!/usr/bin/env -S npx tsx
// Builds every bundled Open Design design system as a Claude Design System
// artifact tree, ready for Claude Design's GitHub and upload routes:
//
//   claude-design-systems/<id>/project/{design-system.json,tokens.json,README.md,components/Cover/preview.html}
//   claude-design-systems/README.md   (the catalogue)
//
//   npx tsx scripts/build-claude-design-systems.ts           write the tree (run by `npm run sync-content`)
//   npx tsx scripts/build-claude-design-systems.ts --check   fail if the tree is stale (run by `npm run lint`)
//
// Generated, never hand-edited. Bundled systems are read through the content
// index, so the local overlays (tokens.override.css, DESIGN.sections.md) apply.
// Dates come from the vendored content's syncedAt, and a file that differs
// only in those dates is left as it is, so a content sync doesn't churn 198 folders.
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { ContentIndex } from '../packages/core/src/content/contentIndex';
import { toClaudeDesignSystem } from '../packages/core/src/generation/claudeDesignSystem';
import { validateClaudeDesignSystem } from '../packages/core/src/generation/claudeDesignSystemFormat';

const REPO = 'feimacode/open-design-agent-kit';
const ROOT = path.resolve(__dirname, '..');
const ASSETS = path.join(ROOT, 'packages/content/assets/open-design');
const OUT = path.join(ROOT, 'claude-design-systems');

interface Built {
  id: string;
  name: string;
  summary: string;
  files: Record<string, string>;
  errors: string[];
  warnings: string[];
}

/** The two index dates and the tokens' sync date move with every content sync; compare without them. */
function withoutDates(file: string, text: string): string {
  if (file.endsWith('design-system.json')) return text.replace(/"at": "[^"]*"/g, '"at": ""');
  if (file.endsWith('tokens.json')) return text.replace(/"synced": "[^"]*"/, '"synced": ""');
  return text;
}

async function buildAll(): Promise<{ built: Built[]; catalogue: string }> {
  const manifest = JSON.parse(await fs.readFile(path.join(ASSETS, 'MANIFEST.json'), 'utf8')) as { sourceRef: string; syncedAt: string };
  const index = new ContentIndex(ASSETS);
  const built: Built[] = [];
  for (const summary of await index.listDesignSystems()) {
    if (summary.source !== 'built-in') continue;
    const ds = await index.getDesignSystem(summary.id);
    if (!ds) continue;
    const tokensCss = ds.tokensCss === undefined ? undefined : ds.tokensOverrideCss ? `${ds.tokensCss}\n${ds.tokensOverrideCss}` : ds.tokensCss;
    const { files } = toClaudeDesignSystem({
      name: ds.name,
      id: ds.id,
      designMd: ds.body,
      tokensCss,
      by: 'Open Design',
      now: manifest.syncedAt,
      via: `Open Design · ${ds.id}@${manifest.sourceRef}`,
      note: 'Built by scripts/build-claude-design-systems.ts.',
      meta: { source: 'github', repo: REPO, package: `claude-design-systems/${ds.id}`, upstream: manifest.sourceRef, synced: manifest.syncedAt.slice(0, 10) },
    });
    const { errors, warnings } = validateClaudeDesignSystem(files);
    built.push({ id: ds.id, name: ds.name, summary: ds.summary, files, errors, warnings });
  }
  built.sort((a, b) => a.id.localeCompare(b.id));
  const cell = (s: string): string => s.replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
  const catalogue = `# Open Design design systems for Claude Design

Generated by \`scripts/build-claude-design-systems.ts\` from the bundled design systems (with this repository's local fixes applied). Don't edit these files: run \`npm run sync-content\`.

Each folder holds a \`project/\` tree in Claude Design's Design System format: \`design-system.json\`, \`tokens.json\`, \`README.md\` and a cover. To use one in Claude:

- **From a GitHub repo:** in Claude, **Settings → Design systems → New design system → Using Claude → Sync from my GitHub repository**; give \`${REPO}\` and pick the system's folder below (for example \`claude-design-systems/kami\`). Claude needs access to your GitHub account.
- **Upload from files:** drop the files of that folder's \`project/\`.
- **Several at once, from Claude Code:** ask "Publish these Open Design design systems to Claude Design: kami, lingo", from a checkout of this repository.

Motion tokens don't carry across, because Claude's format has no motion family. Each README's last section lists what was left out.

| Design system | Folder | Summary |
|---|---|---|
${built.map((b) => `| ${cell(b.name)} | \`claude-design-systems/${b.id}\` | ${cell(b.summary)} |`).join('\n')}
`;
  return { built, catalogue };
}

async function listTree(dir: string): Promise<string[]> {
  const out: string[] = [];
  const walk = async (d: string): Promise<void> => {
    for (const e of await fs.readdir(d, { withFileTypes: true }).catch(() => [])) {
      const p = path.join(d, e.name);
      if (e.isDirectory()) await walk(p);
      else out.push(path.relative(dir, p).split(path.sep).join('/'));
    }
  };
  await walk(dir);
  return out.sort();
}

async function main(): Promise<void> {
  const check = process.argv.includes('--check');
  const { built, catalogue } = await buildAll();
  const problems: string[] = [];
  for (const b of built) for (const e of b.errors) problems.push(`${b.id}: ${e}`);

  const expected = new Map<string, string>([['README.md', catalogue]]);
  for (const b of built) for (const [rel, text] of Object.entries(b.files)) expected.set(`${b.id}/${rel}`, text);
  const existing = await listTree(OUT);

  if (check) {
    const stale = new Set<string>();
    for (const [rel, text] of expected) {
      const current = await fs.readFile(path.join(OUT, rel), 'utf8').catch(() => undefined);
      if (current === undefined) stale.add(`${rel.split('/')[0]} (missing)`);
      else if (withoutDates(rel, current) !== withoutDates(rel, text)) stale.add(rel.includes('/') ? rel.split('/')[0] : 'README.md');
    }
    for (const rel of existing) if (!expected.has(rel)) stale.add(`${rel.split('/')[0]} (not a bundled system, or not a built file)`);
    if (stale.size) problems.push(`claude-design-systems/ is stale for: ${[...stale].join(', ')}. Run npm run sync-content.`);
    if (problems.length) {
      console.error(problems.join('\n'));
      process.exit(1);
    }
    console.log(`claude-design-systems/ is in sync (${built.length} systems).`);
    return;
  }

  if (problems.length) {
    console.error(problems.join('\n'));
    process.exit(1);
  }
  let written = 0;
  for (const [rel, text] of expected) {
    const file = path.join(OUT, rel);
    const current = await fs.readFile(file, 'utf8').catch(() => undefined);
    if (current !== undefined && withoutDates(rel, current) === withoutDates(rel, text)) continue;
    await fs.mkdir(path.dirname(file), { recursive: true });
    await fs.writeFile(file, text);
    written++;
  }
  let removed = 0;
  for (const rel of existing) {
    if (expected.has(rel)) continue;
    await fs.rm(path.join(OUT, rel));
    removed++;
  }
  for (const id of await fs.readdir(OUT)) {
    const dir = path.join(OUT, id);
    if ((await fs.stat(dir)).isDirectory() && (await listTree(dir)).length === 0) await fs.rm(dir, { recursive: true });
  }
  const warned = built.filter((b) => b.warnings.length).length;
  console.log(`Built ${built.length} Claude design systems into claude-design-systems/ (${written} files written, ${removed} removed; ${warned} systems have contrast notes).`);
}

main().catch((err) => {
  console.error(err instanceof Error ? err.message : err);
  process.exit(1);
});
